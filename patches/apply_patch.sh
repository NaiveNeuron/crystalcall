#!/usr/bin/env bash
# Build the instrumented DiffusionGemma sampler for the pinned vLLM image.
#
# Strategy: RUN-TIME BIND MOUNTS (no derived image).
#   1. extract the image's pristine diffusion_gemma.py,
#   2. apply patches/vllm-trace.patch, then patches/vllm-preact.patch, to a
#      copy under patches/build/,
#   3. record the image digest / vLLM version / site-packages path,
#   4. the serve scripts bind-mount the patched file over site-packages and
#      the stdlib-only emitter + priority module onto PYTHONPATH.
#
# Two patches, applied in order, on purpose: the trace patch is load-bearing
# for EVERY arm and is already proven against the pinned image, while the
# preact patch is arm-specific and must stay reviewable (and revertible) on its
# own.  Both land in ONE file, because the same image and the same file must
# serve every arm, switched only by environment variables.
#
# Why bind mounts and not a derived image: the image is ~15 GB on this box, a
# derived layer costs another full copy of the site-packages layer on every
# edit of the patch, and the mount makes "same binary path, tracing off" (the
# baseline requirement) trivially true -- the identical container image and
# identical patched file run both arms, switched only by CRYSTALCALL_TRACE.
#
# Usage:
#   patches/apply_patch.sh            # extract + patch + verify
#   patches/apply_patch.sh --check    # only re-run `patch -p1 --dry-run`
set -euo pipefail

IMAGE="${CRYSTALCALL_VLLM_IMAGE:-vllm/vllm-openai:gemma}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD="$HERE/build"
REL="vllm/model_executor/models/diffusion_gemma.py"
PATCH="$HERE/vllm-trace.patch"
PATCH2="$HERE/vllm-preact.patch"
ORIG="$BUILD/diffusion_gemma.py.orig"
OUT="$BUILD/diffusion_gemma.py"
ENVFILE="$BUILD/image-env.sh"

die() { echo "apply_patch: $*" >&2; exit 1; }

docker image inspect "$IMAGE" >/dev/null 2>&1 || die "image $IMAGE not present locally"
mkdir -p "$BUILD"

# ---- image metadata ------------------------------------------------------- #
DIGEST="$(docker image inspect --format '{{if .RepoDigests}}{{index .RepoDigests 0}}{{else}}{{.Id}}{{end}}' "$IMAGE")"
IMAGE_ID="$(docker image inspect --format '{{.Id}}' "$IMAGE")"
SITE_PACKAGES="$(docker run --rm --entrypoint python3 "$IMAGE" -c \
  'import os, vllm; print(os.path.dirname(os.path.dirname(vllm.__file__)))')"
VLLM_VERSION="$(docker run --rm --entrypoint python3 "$IMAGE" -c \
  'import vllm; print(vllm.__version__)')"

# ---- extract the pristine file ------------------------------------------- #
CID="cc-vllm-extract-$$"
docker rm -f "$CID" >/dev/null 2>&1 || true
docker create --name "$CID" "$IMAGE" >/dev/null
trap 'docker rm -f "$CID" >/dev/null 2>&1 || true' EXIT
docker cp "$CID:$SITE_PACKAGES/$REL" "$ORIG" \
  || die "no $REL in $IMAGE -- this build has no DiffusionGemma implementation"

cat >"$ENVFILE" <<EOF
# generated by patches/apply_patch.sh -- do not edit
CRYSTALCALL_VLLM_IMAGE='$IMAGE'
CRYSTALCALL_VLLM_DIGEST='$DIGEST'
CRYSTALCALL_VLLM_IMAGE_ID='$IMAGE_ID'
CRYSTALCALL_VLLM_VERSION='$VLLM_VERSION'
CRYSTALCALL_SITE_PACKAGES='$SITE_PACKAGES'
CRYSTALCALL_SAMPLER_REL='$REL'
EOF

echo "image      : $IMAGE"
echo "digest     : $DIGEST"
echo "vllm       : $VLLM_VERSION"
echo "site-pkgs  : $SITE_PACKAGES"
echo "pristine   : $ORIG ($(wc -l <"$ORIG") lines, sha256 $(sha256sum "$ORIG" | cut -c1-16))"

[[ -f "$PATCH" ]] || die "missing $PATCH"
[[ -f "$PATCH2" ]] || die "missing $PATCH2"

# ---- dry run, then apply -------------------------------------------------- #
STAGE="$(mktemp -d)"
trap 'docker rm -f "$CID" >/dev/null 2>&1 || true; rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/$(dirname "$REL")"
cp "$ORIG" "$STAGE/$REL"

( cd "$STAGE" && patch -p1 --dry-run <"$PATCH" ) || die "vllm-trace.patch -p1 --dry-run FAILED against the image's pristine file"
echo "dry-run    : vllm-trace.patch OK"

# The preact patch is written against the trace-patched file, so it must be
# dry-run on top of a real application of the first patch.
( cd "$STAGE" && patch -p1 <"$PATCH" ) >/dev/null
( cd "$STAGE" && patch -p1 --dry-run <"$PATCH2" ) || die "vllm-preact.patch -p1 --dry-run FAILED against the trace-patched file"
echo "dry-run    : vllm-preact.patch OK"

if [[ "${1:-}" == "--check" ]]; then
  exit 0
fi

( cd "$STAGE" && patch -p1 <"$PATCH2" ) >/dev/null
python3 -m py_compile "$STAGE/$REL" || die "patched file does not compile"
cp "$STAGE/$REL" "$OUT"
echo "patched    : $OUT ($(wc -l <"$OUT") lines, sha256 $(sha256sum "$OUT" | cut -c1-16))"

# Also verify both patches apply with the image's own `patch` when it has one
# -- that is the environment that actually runs the code.  The second patch is
# written against the output of the first, so the check stages the single file
# in a scratch tree and applies them in order.
if docker run --rm --entrypoint bash "$IMAGE" -c 'command -v patch >/dev/null'; then
  docker run --rm --entrypoint bash \
    -v "$HERE:/cc:ro" -e "CC_REL=$REL" -e "CC_SITE=$SITE_PACKAGES" "$IMAGE" -c '
      set -e
      mkdir -p "/tmp/cc-stage/$(dirname "$CC_REL")"
      cp "$CC_SITE/$CC_REL" "/tmp/cc-stage/$CC_REL"
      cd /tmp/cc-stage
      patch -p1 --forward </cc/vllm-trace.patch
      patch -p1 --dry-run --forward </cc/vllm-preact.patch
    ' >/dev/null \
    && echo "in-image   : patch -p1 --dry-run OK (both patches)"
else
  echo "in-image   : skipped (no patch(1) in image; host dry-run used the byte-identical extract)"
fi

echo
echo "mount with:"
echo "  -v $OUT:$SITE_PACKAGES/$REL:ro"
echo "  -v $HERE/crystalcall_trace.py:/opt/crystalcall/crystalcall_trace.py:ro"
echo "  -v $HERE/preact_priority.py:/opt/crystalcall/crystalcall_preact.py:ro"
echo "  -e PYTHONPATH=/opt/crystalcall"
